begin;

create table if not exists public.apm_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.apm_admins enable row level security;
revoke all on public.apm_admins from anon, authenticated;
grant select on public.apm_admins to authenticated;
drop policy if exists apm_admin_self on public.apm_admins;
create policy apm_admin_self on public.apm_admins for select to authenticated
using (user_id = (select auth.uid()));

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 160),
  ref text not null default '' check (length(ref) <= 100),
  category text not null check (length(trim(category)) between 1 and 80),
  price numeric(12,2) check (price >= 0 and price <= 10000000),
  image text not null check (length(image) between 1 and 2048 and image !~ '[<>"''[:space:]]'),
  description text not null default '' check (length(description) <= 3000),
  availability text not null default 'Sur demande'
    check (availability in ('Sur demande','Disponible','Indisponible')),
  active boolean not null default true,
  version integer not null default 1,
  efface text not null default 'Non' check (efface in ('Oui','Non')),
  date_suppression timestamptz,
  check (efface = 'Non' or date_suppression is not null)
);
alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;
grant select on public.products to anon, authenticated;
grant insert, update on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

drop policy if exists apm_public_read on public.products;
create policy apm_public_read on public.products for select to anon, authenticated
using (active and efface = 'Non');
drop policy if exists apm_admin_read on public.products;
create policy apm_admin_read on public.products for select to authenticated
using (exists (select 1 from public.apm_admins where user_id = (select auth.uid())));
drop policy if exists apm_admin_insert on public.products;
create policy apm_admin_insert on public.products for insert to authenticated
with check (exists (select 1 from public.apm_admins where user_id = (select auth.uid())));
drop policy if exists apm_admin_update on public.products;
create policy apm_admin_update on public.products for update to authenticated
using (exists (select 1 from public.apm_admins where user_id = (select auth.uid())))
with check (exists (select 1 from public.apm_admins where user_id = (select auth.uid())));
-- Aucun droit DELETE : la corbeille conserve les fiches.

create or replace function public.apm_product_change()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.version := old.version + 1;
  if old.efface = 'Non' and new.efface = 'Oui' then
    new.date_suppression := now();
  elsif old.efface = 'Oui' and new.efface = 'Non' then
    new.active := false;
    new.date_suppression := old.date_suppression;
  else
    new.date_suppression := old.date_suppression;
  end if;
  return new;
end;
$$;
drop trigger if exists apm_product_change on public.products;
create trigger apm_product_change before update on public.products
for each row execute function public.apm_product_change();

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('product-images','product-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

drop policy if exists apm_images_admin_insert on storage.objects;
create policy apm_images_admin_insert on storage.objects for insert to authenticated
with check (bucket_id = 'product-images' and
exists (select 1 from public.apm_admins where user_id = (select auth.uid())));
drop policy if exists apm_images_admin_read on storage.objects;
create policy apm_images_admin_read on storage.objects for select to authenticated
using (bucket_id = 'product-images' and
exists (select 1 from public.apm_admins where user_id = (select auth.uid())));
